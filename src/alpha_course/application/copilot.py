_CAPABILITIES = re.compile(
    r"(какие|что|чего)\s+(у\s+тебя\s+)?(функци\w*|умеешь|можешь|ты\s+можешь|ты\s+умеешь)"
    r"|(что|чем)\s+(ты\s+)?(умеешь|можешь|полезен)|^\s*(помощь|помоги|функции|возможности)\s*[?!.]*\s*$"
    r"|на\s+что\s+ты\s+способен|расскажи\s+(о\s+себе|что\s+умеешь)",
    re.I,
)


def is_capabilities_question(text: str) -> bool:
    return bool(_CAPABILITIES.search(text.strip()[:200]))


def capabilities_text() -> str:
    """HTML for the chat: groups, titles and one example each."""
    lines = [
        "🤖 <b>Я — твой личный ИИ-ассистент по бизнесу</b>",
        "Знаю твой профиль, помню ход разговора, ищу в интернете и делаю PDF. Просто напиши задачу своими словами.\n",
    ]
    for group, items in SKILLS:
        lines.append(f"<b>{group}</b>")
        lines.extend(f"• <b>{title}</b> — {hint}" for title, hint in items)
        lines.append("")
    lines.append("Примеры: «найди 5 конкурентов кофеен в Казани», «составь бизнес-план в PDF», «какая сейчас ставка взносов для ИП».")
    return "\n".join(lines)[:3900]


def skills_prompt() -> str:
    return "\n".join(f"- {group}: " + "; ".join(title for title, _ in items) for group, items in SKILLS)


def profile_context(profile: BusinessProfile) -> dict[str, str]:
    """Everything known about the person's business, in words; free text is masked."""
    result: dict[str, str] = {}
    for name, label in FIELD_LABELS.items():
        value = getattr(profile, name, None)
        if value in (None, ""):
            continue
        if name == "employees":
            value = "есть сотрудники" if value else "без сотрудников"
        elif name == "level":
            value = LEVEL_LABELS.get(value, value)
        result[name] = mask_personal(str(value), limit=200)
    return result


def personalization_note(profile: BusinessProfile) -> str:
    known = profile_context(profile)
    if not known:
        return "Пока не знаю твой бизнес — заполни «👤 Профиль», и советы станут точнее."
    return "🎯 Учтено: " + ", ".join(known.values())
